/** The deck's clue for a scale (or null for scales without one). */
export const clueFor = (left: string, right: string): string | null => DECK_CLUES[`${left}|${right}`] ?? null;

/** Everything 🎲 can suggest: the hand-picked examples plus the whole deck with its clues. */
export const ALL_SUGGESTIONS: { left: string; right: string; clue: string }[] = [
  ...EXAMPLES,
  ...Object.entries(DECK_CLUES)
    .map(([k, clue]) => {
      const [left, right] = k.split('|');
      return { left, right, clue };
    })
    .filter((d) => !EXAMPLES.some((e) => e.left === d.left && e.right === d.right)),
];
